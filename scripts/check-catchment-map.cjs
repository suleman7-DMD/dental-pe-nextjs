// Live-data browser acceptance. node scripts/check-catchment-map.cjs [URL]
const { chromium, expect } = require('@playwright/test')
;(async () => {
  const base = process.argv[2] || 'http://localhost:3104'
  const browser = await chromium.launch({ headless: true,
    executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    args: ['--enable-unsafe-swiftshader'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1500, height: 1050 } })
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    const routes = []; page.on('request', r => { if (r.url().includes('/api/catchment?')) routes.push(r.url()) })
    await page.goto(base + '/directory?tab=map', { waitUntil: 'domcontentloaded', timeout: 120000 })
    await page.getByRole('button', { name: 'Explore drive-time catchments' }).click({ timeout: 120000 })
    const panel = page.getByRole('region', { name: 'Catchment research' })
    await expect(panel).toBeVisible()
    await panel.getByRole('combobox', { name: 'Choose a research corridor' }).selectOption('lockport')
    const competition = page.getByRole('region', { name: 'Catchment competition' })
    const households = page.getByRole('region', { name: 'Catchment households' })
    await expect(competition).toBeVisible({ timeout: 120000 })
    await expect(households).toBeVisible({ timeout: 120000 })
    await expect(households).not.toContainText('—')
    console.log('LOCKPORT 15', (await competition.innerText()).replaceAll('\n', ' | '))
    console.log('HOUSEHOLDS', (await households.innerText()).replaceAll('\n', ' | '))
    await page.screenshot({ path: '/tmp/dental-catchment-desktop.png', fullPage: true })
    console.log('MARKERS', await page.locator('.catchment-origin').evaluateAll(els => els.map(el => el.outerHTML)), 'ERRORS', errors)
    await expect(page.locator('.catchment-origin')).toBeVisible()
    const before = await competition.textContent()
    await page.getByRole('group', { name: 'Map status filters' }).getByRole('button').nth(1).click()
    await expect(competition).toHaveText(before)
    await page.getByRole('textbox', { name: 'Search directory' }).fill('not-a-real-office')
    await expect(competition).toHaveText(before)
    await page.getByRole('button', { name: 'Clear search' }).click()
    await panel.getByRole('button', { name: '10 minutes core' }).click()
    await expect(competition).not.toHaveText(before)
    expect(new URL(page.url()).searchParams.get('drive')).toBe('10')
    await panel.getByRole('button', { name: 'Save node' }).click()
    await panel.getByRole('combobox', { name: 'Choose a research corridor' }).selectOption('bartlett')
    await expect(panel.getByRole('heading', { name: 'Stearns Road · Bartlett' })).toBeVisible()
    await expect(households).toBeVisible({ timeout: 120000 })
    await panel.getByRole('button', { name: 'Save node' }).click()
    await panel.getByRole('button', { name: /Compare/ }).click()
    await expect(panel).toContainText('Median HH income')
    await page.screenshot({ path: '/tmp/dental-catchment-compare.png', fullPage: true })
    await page.reload({ waitUntil: 'domcontentloaded' })
    await expect(page.getByRole('heading', { name: 'Stearns Road · Bartlett' })).toBeVisible({ timeout: 120000 })
    await expect(panel.getByRole('button', { name: /Compare 2\/3/ })).toBeVisible()
    await expect(competition).toBeVisible({ timeout: 120000 })
    await panel.getByRole('button', { name: 'Acquisition context', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Catchment acquisition context' })).toContainText('Linked individual NPI records')
    const downloadEvent = page.waitForEvent('download')
    await panel.getByRole('button', { name: 'Study JSON', exact: true }).click()
    const download = await downloadEvent; await download.saveAs('/tmp/dental-catchment-study.json')
    const report = JSON.parse(require('node:fs').readFileSync('/tmp/dental-catchment-study.json', 'utf8'))
    expect(report.minutes).toBe(10); expect(report.geometry.features).toHaveLength(2)
    expect(report.supply.offices.length).toBe(report.supply.possible)
    await panel.getByRole('button', { name: 'Households & competition' }).click()
    await panel.getByRole('button', { name: 'Inspect residential land underneath' }).click()
    expect(new URL(page.url()).searchParams.get('mapLayer')).toBe('landuse')
    await page.screenshot({ path: '/tmp/dental-catchment-homes.png', fullPage: true })

    await page.setViewportSize({ width: 390, height: 844 })
    await expect(panel).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: '/tmp/dental-catchment-mobile.png', fullPage: true })
    await panel.getByRole('button', { name: 'Collapse catchment panel' }).click()
    await expect(panel.getByRole('button', { name: 'Expand catchment panel' })).toBeVisible()
    await panel.getByRole('button', { name: 'Expand catchment panel' }).click()
    await panel.getByRole('button', { name: 'Drop pin', exact: true }).click()
    const canvas = page.locator('.mapboxgl-canvas'); const box = await canvas.boundingBox()
    await page.mouse.click(box.x + box.width * .4, box.y + box.height * .28)
    await expect(panel.getByRole('heading', { name: 'Dropped pin', exact: true })).toBeVisible()
    await expect(competition).toBeVisible({ timeout: 120000 })
    await page.screenshot({ path: '/tmp/dental-catchment-mobile-pin.png', fullPage: true })
    expect(errors).toEqual([])
    console.log('PASS actual routing, Census, filter independence, windows, save/restore, export, homes and mobile pin placement')

    const failed = await browser.newPage()
    await failed.route('**/api/catchment?**', r => r.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Routing temporarily unavailable' }) }))
    await failed.goto(base + '/directory?tab=map&catchment=-88.01111,41.59807&node=Failure-test', { waitUntil: 'domcontentloaded', timeout: 120000 })
    await expect(failed.getByRole('alert').filter({ hasText: /\S/ })).toContainText('Routing temporarily unavailable', { timeout: 120000 })
    await expect(failed.getByRole('region', { name: 'Catchment competition' })).toHaveCount(0)
    await failed.unroute('**/api/catchment?**')
    await failed.getByRole('button', { name: 'Retry routing' }).click()
    await expect(failed.getByRole('region', { name: 'Catchment competition' })).toBeVisible({ timeout: 120000 })
    console.log('PASS routing outage fails visibly and retry recovers; requests:', routes.length)
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
